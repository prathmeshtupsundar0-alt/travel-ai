require('dotenv').config()
const express = require('express')
const cors = require('cors')
const helmet = require('helmet')
const rateLimit = require('express-rate-limit')
const cookieParser = require('cookie-parser')
const connectDatabase = require('./config/db')
const authRoutes = require('./routes/authRoutes')
const tripRoutes = require('./routes/tripRoutes')
const expenseRoutes = require('./routes/expenseRoutes')
const aiRoutes = require('./routes/aiRoutes')
const userRoutes = require('./routes/userRoutes')
const tripDataRoutes = require('./routes/tripDataRoutes')
const { notFound, errorHandler } = require('./middleware/errorMiddleware')

const required = ['MONGODB_URI', 'JWT_SECRET', 'FRONTEND_URL']
for (const variable of required) if (!process.env[variable]) throw new Error(`${variable} is required. Add it to backend/.env.`)
if (process.env.JWT_SECRET.length < 32) throw new Error('JWT_SECRET must be at least 32 characters long.')

const app = express()
app.use(helmet())
app.use(cors({ origin: process.env.FRONTEND_URL, credentials: true, methods: ['GET', 'POST', 'PUT', 'PATCH', 'DELETE'] }))
app.use(express.json({ limit: '1mb' }))
app.use(cookieParser())
app.use(rateLimit({ windowMs: 15 * 60 * 1000, max: 300, standardHeaders: true, legacyHeaders: false, message: { success: false, message: 'Too many requests. Please try again later.' } }))

app.get('/api/health', (req, res) => res.json({ success: true, message: 'Traveling AI API is running', database: require('mongoose').connection.readyState === 1 ? 'connected' : 'disconnected' }))
app.use('/api/auth', authRoutes)
app.use('/api/trips', tripRoutes)
app.use('/api/expenses', expenseRoutes)
app.use('/api/ai', aiRoutes)
app.use('/api/users', userRoutes)
app.use('/api/trip-data', tripDataRoutes)
app.use(notFound)
app.use(errorHandler)

const port = Number(process.env.PORT) || 5000
connectDatabase().then(() => app.listen(port, () => console.log(`Server running on http://localhost:${port}`)))
